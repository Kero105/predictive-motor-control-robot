"""
Terrain Classifier Training + C++ Export
Trains a real decision tree classifier (avg_current, accel_variance) -> terrain,
replacing the hand-tuned two-threshold rule in the firmware, then auto-exports
the trained tree as nested if/else C++ code you can paste directly into the ESP32 firmware.

CURRENTLY uses DUMMY labeled data (same generation logic as analyze_controllers.py)
so the full training + export pipeline is built and tested before real bench data exists.

TO USE WITH REAL DATA:
  Replace generate_dummy_training_data() with real (current, accel_variance, terrain)
  triples collected during your Phase 2 bench-testing on each actual terrain.
"""

import numpy as np
from sklearn.tree import DecisionTreeClassifier, export_text
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report

TERRAIN_LABELS = ["smooth", "carpet", "ramp"]


def generate_dummy_training_data(n_samples=600, seed=7):
    """Simulates (avg_current, accel_variance) feature pairs per terrain, with
    realistic overlap/noise so the trained tree isn't trivially perfect --
    matches the same rough behavior as the rule-based classifier it replaces."""
    rng = np.random.default_rng(seed)
    X, y = [], []

    # Rough per-terrain feature distributions (current in A, accel variance in m^2/s^4-ish units)
    terrain_params = {
        "smooth": {"current_mean": 0.35, "current_std": 0.08, "accelvar_mean": 0.3, "accelvar_std": 0.2},
        "carpet": {"current_mean": 0.65, "current_std": 0.12, "accelvar_mean": 0.8, "accelvar_std": 0.4},
        "ramp":   {"current_mean": 0.55, "current_std": 0.15, "accelvar_mean": 2.5, "accelvar_std": 0.6},
    }

    per_class = n_samples // len(TERRAIN_LABELS)
    for terrain in TERRAIN_LABELS:
        p = terrain_params[terrain]
        currents = rng.normal(p["current_mean"], p["current_std"], per_class)
        accelvars = np.abs(rng.normal(p["accelvar_mean"], p["accelvar_std"], per_class))
        for c, a in zip(currents, accelvars):
            X.append([c, a])
            y.append(terrain)

    return np.array(X), np.array(y)


def train_classifier(X, y, max_depth=4):
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, random_state=42, stratify=y)

    clf = DecisionTreeClassifier(max_depth=max_depth, random_state=42)
    clf.fit(X_train, y_train)

    y_pred = clf.predict(X_test)
    acc = accuracy_score(y_test, y_pred)
    print(f"Test accuracy: {acc:.3f}\n")
    print("Classification report:")
    print(classification_report(y_test, y_pred))
    print("Confusion matrix (rows=true, cols=predicted), classes:", clf.classes_)
    print(confusion_matrix(y_test, y_pred))
    print("\nTree structure (human-readable):")
    print(export_text(clf, feature_names=["avg_current", "accel_variance"]))

    return clf


def export_tree_to_cpp(clf, feature_names=("avgCurrent", "accelVariance")):
    """
    Walks the trained sklearn decision tree and generates equivalent nested
    if/else C++ code, returning terrain class NAMES matching the firmware's
    TerrainClass enum (TERRAIN_SMOOTH / TERRAIN_CARPET / TERRAIN_RAMP).
    """
    tree = clf.tree_
    class_names = clf.classes_

    label_to_enum = {
        "smooth": "TERRAIN_SMOOTH",
        "carpet": "TERRAIN_CARPET",
        "ramp": "TERRAIN_RAMP",
    }

    lines = []
    lines.append("// AUTO-GENERATED by train_terrain_classifier.py -- DO NOT hand-edit, regenerate instead.")
    lines.append("// Trained DecisionTreeClassifier, exported to nested if/else for embedded use.")
    lines.append("TerrainClass classifyTerrain_trained(float avgCurrent, float accelVariance) {")

    def recurse(node, depth):
        indent = "  " * (depth + 1)
        if tree.feature[node] != -2:  # -2 means leaf node in sklearn's tree_ structure
            feat = feature_names[tree.feature[node]]
            threshold = tree.threshold[node]
            lines.append(f"{indent}if ({feat} <= {threshold:.5f}f) {{")
            recurse(tree.children_left[node], depth + 1)
            lines.append(f"{indent}}} else {{")
            recurse(tree.children_right[node], depth + 1)
            lines.append(f"{indent}}}")
        else:
            class_idx = np.argmax(tree.value[node])
            predicted_label = class_names[class_idx]
            enum_name = label_to_enum.get(predicted_label, "TERRAIN_UNKNOWN")
            lines.append(f"{indent}return {enum_name};")

    recurse(0, 0)
    lines.append("}")
    return "\n".join(lines)


if __name__ == "__main__":
    print("Training terrain classifier on DUMMY data (replace with real bench-test data when ready)\n")
    X, y = generate_dummy_training_data()
    clf = train_classifier(X, y)

    cpp_code = export_tree_to_cpp(clf)
    with open("terrain_classifier_trained.h", "w") as f:
        f.write("#pragma once\n\n")
        f.write(cpp_code)
        f.write("\n")

    print("\n" + "=" * 60)
    print("Exported trained classifier to terrain_classifier_trained.h")
    print("=" * 60)
    print("\nGenerated C++ code:\n")
    print(cpp_code)
